#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""dump_cuts.py -- emit the EFFECTIVE analysis cuts as markdown.

Generated from p2_qa_config at import time, so the document can never drift
from what the stages actually applied. Run it the same way you run the
pipeline (i.e. with P2_MINIMAL_CUTS set or not) and it reports that profile.

    python3 dump_cuts.py                     # -> stdout
    P2_MINIMAL_CUTS=1 python3 dump_cuts.py -o CUTS.md
"""

import argparse
import datetime
import os
import sys

import p2_qa_config as C

# Which run keys are built on the August-2026 reprocessed data. The rest are
# on the old reconstruction and are NOT part of the re-analysis.
OLD_RECO_KEYS = {
    'det1_long2':        'run 7-4-26 is not on rays; raw gone, cannot reprocess',
    'det4_long1':        'run 7-15-26 purged from rays 2026-07-16; raw gone',
    'det4_long1_stable': 'windowed variant of det4_long1 (same purged run)',
    'det2_fe55scan1':    'banco bench Fe55; raw never on rays',
    'det3_fe55scan1':    'banco bench Fe55; raw never on rays',
}
WINDOWED_KEYS = {'det1_long5_pre', 'det1_long5_post', 'det4_long1_stable'}

SCAN_KINDS = {'hv_scan': 'mesh scan', 'drift_scan': 'drift scan',
              'mesh_scan': 'mesh scan', 'fe55_scan': 'Fe55 scan'}


def kind(cfg):
    return SCAN_KINDS.get(cfg.SUB_RUN, 'long run')


def fmt(v):
    if v is None:
        return '-'
    if isinstance(v, tuple):
        return ','.join(str(x) for x in v) if v else '-'
    if isinstance(v, float) and v == int(v):
        return str(int(v))
    return str(v)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('-o', '--out', default=None)
    args = ap.parse_args()

    out = []
    w = out.append
    profile = 'MINIMAL' if C.MINIMAL_CUTS else 'TUNED (per-run, as registered)'
    w('# P2 cosmic-bench analysis — cuts in force')
    w('')
    w('_Generated by `dump_cuts.py` from `p2_qa_config.py`. '
      'Regenerate after changing any cut._')
    w('')
    w(f'- **Profile:** `{profile}`'
      + ('  (`P2_MINIMAL_CUTS=1`)' if C.MINIMAL_CUTS else ''))
    w(f'- **Generated:** {datetime.datetime.now().strftime("%Y-%m-%d %H:%M")}')
    w(f'- **DATA_ROOT:** `{C.DATA_ROOT}`')
    w(f'- **ANALYSIS_ROOT:** `{C.ANALYSIS_ROOT}`')
    w('')

    w('## Global reference-track cuts (all detectors, all stages)')
    w('')
    w('| cut | value | meaning |')
    w('|---|---|---|')
    w(f'| `M3_CHI2_CUT` | {C.M3_CHI2_CUT} | max Chi2X/Chi2Y of an M3 reference '
      'ray. Loose end of the useful range; tighten to 1 for a resolution study. |')
    w(f'| `M3_MIN_NCLUS` | {C.M3_MIN_NCLUS} | min clusters per coordinate. '
      '**Correctness requirement, not a quality cut** — a 2-point fit is exact '
      'and carries a denormal chi2 that slips through any chi2 threshold. |')
    w('')

    w('## Per-run cuts')
    w('')
    w('`dead_conn` = physically disconnected connectors, dropped from the pad '
      'map. Keeping them would score tracks pointing at absent electronics as '
      'misses and bias efficiency **down** — geometry, not a cut.')
    w('')
    w('| run key | det | kind | dead_conn | min_amp | t_min..t_max [h] | '
      'noisy_pads | hot_ratio | burst_npads | match_R [mm] | spark thr [uA] |')
    w('|---|---|---|---|---|---|---|---|---|---|---|')
    for k, c in C.RUNS.items():
        if k in OLD_RECO_KEYS:
            continue
        win = f'{fmt(c.T_MIN_H)}..{fmt(c.T_MAX_H)}'
        note = ' _(windowed)_' if k in WINDOWED_KEYS else ''
        w(f'| `{k}`{note} | {c.DET_TAG} | {kind(c)} | {fmt(c.DEAD_CONNECTORS)} '
          f'| {fmt(c.MIN_AMP)} | {win} | {fmt(c.NOISY_PADS)} '
          f'| {fmt(c.HOT_PAD_RATIO)} | {fmt(c.BURST_NPADS)} '
          f'| {fmt(c.MATCH_R)} | {fmt(c.SPARK_IMON_THR)} |')
    w('')

    w('## What the minimal profile relaxes')
    w('')
    w('| field | minimal value | what it disables |')
    w('|---|---|---|')
    w('| `MIN_AMP` | 0 | amplitude floor — every hit kept |')
    w('| `NOISY_PADS` | () | hand-listed pad exclusions |')
    w('| `HOT_PAD_RATIO` | 0 | automatic hot-pad drop |')
    w('| `BURST_NPADS` | 0 | high-multiplicity burst veto |')
    w('| `T_MIN_H`/`T_MAX_H` | None | analysis time window — full run used |')
    w('')
    w('Kept regardless: `DEAD_CONNECTORS`, `MATCH_R`, the HV spark veto '
      '(every veto-capable stage is run **both** ways, so the un-vetoed '
      'products are the true minimal-cut view), and the global M3 cuts above.')
    w('')
    if C.MINIMAL_CUT_CHANGES:
        w(f'### Changes applied vs the registered values ({len(C.MINIMAL_CUT_CHANGES)})')
        w('')
        w('| run key | field | registered | minimal |')
        w('|---|---|---|---|')
        for k, f, o, n in C.MINIMAL_CUT_CHANGES:
            if k in OLD_RECO_KEYS:
                continue
            w(f'| `{k}` | `{f}` | {fmt(o)} | {fmt(n)} |')
        w('')

    w('## Excluded from this re-analysis (old reconstruction)')
    w('')
    w('These cannot be reprocessed — their raw `.fdf` is gone or was never on '
      'rays — so they still carry pre-August hit finding and are **not** '
      'comparable with the runs above.')
    w('')
    w('| run key | det | why |')
    w('|---|---|---|')
    for k, why in OLD_RECO_KEYS.items():
        w(f'| `{k}` | {C.RUNS[k].DET_TAG} | {why} |')
    w('')

    text = '\n'.join(out) + '\n'
    if args.out:
        with open(args.out, 'w') as fh:
            fh.write(text)
        print(f'wrote {args.out} ({len(text)} B)', file=sys.stderr)
    else:
        sys.stdout.write(text)


if __name__ == '__main__':
    main()
